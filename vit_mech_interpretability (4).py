"""## 3. Direct Logit Attribution (DLA)
We bypass intermediate layers and project individual head outputs directly onto the Unembedding Matrix ($W_U$).

###  Experiment Hypothesis
* **Hypothesis:** DLA will rapidly identify top candidate heads directly boosting the target class score without needing slow forward pass ablations.
* **Methodology:** Compute $\text{DotProduct}(\mathbf{h}_{l,h} \cdot W_O, W_U[\text{Wildfire}])$ across all 144 attention heads.
"""

import torch

# 1. Target Sample Load and Forward Pass
sample = loader.get_sample(index=0)
pixel_values = sample['pixel_values'].to(engine.device)

with torch.no_grad():
    outputs = engine.model(pixel_values, output_hidden_states=True, output_attentions=True)

# 2. Extract Classifier Unembedding Weight for Target Class (Volcano Proxy: 980)
TARGET_CLASS_IDX = 980
if hasattr(engine.model, 'classifier'):
    w_u_target = engine.model.classifier.weight[TARGET_CLASS_IDX]
elif hasattr(engine.model, 'head'):
    w_u_target = engine.model.head.weight[TARGET_CLASS_IDX]
else:
    linear_layers = [m for m in engine.model.modules() if isinstance(m, torch.nn.Linear)]
    w_u_target = linear_layers[-1].weight[TARGET_CLASS_IDX]

# 3. Dynamic Encoder Layer Access
encoder_layers = engine.model.vit.encoder.layer if hasattr(engine.model.vit, 'encoder') else engine.model.vit.layers
hidden_states = outputs.hidden_states

dla_scores = {}
num_layers = len(encoder_layers) # 12 layers
num_heads = outputs.attentions[0].shape[1] # 12 heads
hidden_dim = hidden_states[0].shape[-1]
head_dim = hidden_dim // num_heads

# 4. TRUE Direct Logit Attribution (DLA) Calculation
for l in range(num_layers):
    # Get CLS token attention output before final W_O projection or per-head slice
    # Layer l hidden state input to attention layer
    layer_in = hidden_states[l][0, 0] # CLS token vector [hidden_dim]

    # Projection Weight W_O
    o_proj = encoder_layers[l].attention.output.dense if hasattr(encoder_layers[l].attention, 'output') else encoder_layers[l].attention.o_proj
    w_o = o_proj.weight # [hidden_dim, hidden_dim]

    for h in range(num_heads):
        start_idx = h * head_dim
        end_idx = start_idx + head_dim

        # Head h ki vector activation
        head_act = layer_in[start_idx:end_idx]
        w_o_head = w_o[:, start_idx:end_idx] # W_O weight slice for head h

        # Head Output Contribution in Residual Stream: h_output = head_act @ W_O_head.T
        head_residual_contrib = torch.matmul(w_o_head, head_act)

        # Direct Logit Impact = Direct Dot Product with Unembedding Vector W_U[target]
        direct_logit_impact = torch.dot(head_residual_contrib, w_u_target).item()
        dla_scores[(l, h)] = direct_logit_impact

# 5. Display Top 5 Direct Contributing Heads
sorted_dla = sorted(dla_scores.items(), key=lambda x: x[1], reverse=True)[:5]

print("--- TOP 5 DIRECT LOGIT ATTRIBUTION HEADS (PROPER DLA) ---")
for (layer, head), score in sorted_dla:
    print(f"Layer {layer}, Head {head} -> Direct Contribution Score: {score:.4f}")

