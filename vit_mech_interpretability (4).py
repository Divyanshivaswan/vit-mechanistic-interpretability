"""# 6. Circuit Isolation — Path Patching Analysis (Target vs. Control Edge)

Having identified Layer 5 Head 8 (Feature Head) and Layer 11 Head 0 (Decision Head), we apply **Path Patching** to isolate direct communication along the $L5H8 \rightarrow L11H0$ channel and validate its specificity against a baseline control edge ($L1H1 \rightarrow L11H0$).

### 💡 Experiment Hypothesis
* **Hypothesis:** Patching activation vectors along $L5H8 \rightarrow L11H0$ will yield a significantly higher causal effect score than patching an arbitrary control edge ($L1H1 \rightarrow L11H0$), proving edge specificity.
* **Methodology:** Dual-hook intervention swapping clean activation buffers with corrupted buffers along the target path versus a baseline control path.
"""

# Real Dynamic Path Patching Execution via PyTorch Hooks
clean_sample = loader.get_sample(index=0) # Wildfire Sample
corrupt_sample = loader.get_sample(index=1) # Non-Wildfire Sample

clean_pixels = clean_sample['pixel_values'].to(engine.device)
corrupt_pixels = corrupt_sample['pixel_values'].to(engine.device)

# 1. Clean & Corrupt Run Baseline Target Logits (Class 980: Volcano Proxy)
with torch.no_grad():
    clean_logits = engine.model(clean_pixels).logits[0, 980].item()
    corrupt_logits = engine.model(corrupt_pixels).logits[0, 980].item()

# Function to perform dynamic path intervention
def measure_edge_patching(src_layer, src_head, tgt_layer, tgt_head):
    saved_corrupt_activation = {}

    # Hook 1: Capture Source Head Activation from Corrupt Image
    def capture_src_hook(module, input, output):
        # Attention output is a Tuple (tensor, attn_weights), so we unpack output[0]
        act_tensor = output[0] if isinstance(output, tuple) else output
        saved_corrupt_activation['val'] = act_tensor.clone()

    # Hook 2: Patch activation into Target Layer during Clean Pass
    def patch_tgt_hook(module, input, output):
        if 'val' in saved_corrupt_activation:
            is_tuple = isinstance(output, tuple)
            act_tensor = output[0] if is_tuple else output

            head_dim = act_tensor.shape[-1] // 12
            s_idx = src_head * head_dim
            e_idx = s_idx + head_dim

            # Replace target slice with corrupt slice
            act_tensor[:, :, s_idx:e_idx] = saved_corrupt_activation['val'][:, :, s_idx:e_idx]

            if is_tuple:
                return (act_tensor,) + output[1:]
            return act_tensor

    # Register Hooks Dynamically
    layers = engine.model.vit.encoder.layer if hasattr(engine.model.vit, 'encoder') else engine.model.vit.layers
    h1 = layers[src_layer].attention.register_forward_hook(capture_src_hook)

    # Corrupt Pass to Record Activations
    with torch.no_grad():
        _ = engine.model(corrupt_pixels)
    h1.remove()

    h2 = layers[tgt_layer].attention.register_forward_hook(patch_tgt_hook)
    # Clean Pass with Intercepted Path
    with torch.no_grad():
        patched_logits = engine.model(clean_pixels).logits[0, 980].item()
    h2.remove()

    # Calculate Causal Path Drop Score
    path_score = (clean_logits - patched_logits) / (clean_logits - corrupt_logits + 1e-8)
    return max(0.0, min(1.0, path_score))

# Execute real path intervention for Target vs Control
path_effect_score = measure_edge_patching(src_layer=5, src_head=8, tgt_layer=11, tgt_head=0)
control_path_score = measure_edge_patching(src_layer=1, src_head=1, tgt_layer=11, tgt_head=0)

